export function tr(lang, key, vars) {
  const table = COPY[lang] || COPY.en;
  let s = table[key] ?? COPY.en[key] ?? key;
  for (const [k, v] of Object.entries(vars || {})) s = s.replace("{" + k + "}", String(v));
  return s;
}
